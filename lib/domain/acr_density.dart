/// Тип плотности молочной железы по классификации ACR (A-D).
enum AcrDensity {
  a,
  b,
  c,
  d;

  String get code => switch (this) {
        AcrDensity.a => 'ACR-A',
        AcrDensity.b => 'ACR-B',
        AcrDensity.c => 'ACR-C',
        AcrDensity.d => 'ACR-D',
      };

  /// Первое предложение блока "Описание" — фиксируется по категории.
  String get densitySentence => switch (this) {
        AcrDensity.a =>
          'Тип плотности ACR-A (железистый компонент менее 25%), соответствует возрасту.',
        AcrDensity.b =>
          'Тип плотности ACR-B (железистый компонент 25-50%), соответствует возрасту.',
        AcrDensity.c =>
          'Тип плотности ACR-C (железистый компонент 51-75%), соответствует возрасту.',
        AcrDensity.d =>
          'Тип плотности ACR-D (железистый компонент более 75%), соответствует возрасту.',
      };

  /// Стандартное описание характера ткани для этой плотности.
  /// Может быть переопределено находкой (например ФЖИ/ФКМ).
  String get defaultStructureSentence => switch (this) {
        AcrDensity.a =>
          'Структура представлена преимущественно элементами жировой ткани, в меньшей степени железистой и фиброзной.',
        AcrDensity.b =>
          'Структура представлена чередованием жировой и железистой ткани с отдельными участками фиброза.',
        AcrDensity.c =>
          'Структура представлена неоднородным чередованием железистой, фиброзной и жировой ткани.',
        AcrDensity.d =>
          'Структура представлена преимущественно элементами железистой ткани, в меньшей степени фиброзной и жировой.',
      };

  /// При плотности C/D рентгенологическая чувствительность снижена —
  /// автоматически рекомендуем УЗИ как дополнение (без лишнего клика).
  bool get requiresAdjunctUltrasound =>
      this == AcrDensity.c || this == AcrDensity.d;
}
